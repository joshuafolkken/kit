import { describe, expect, it } from 'vitest'
import { build_steps } from './build'
import { PUBLIC_LIBRARIES } from './build-library'

function step_names(): Array<string> {
	return build_steps().map((step) => step.name)
}

describe('build_steps', () => {
	it('runs the bin, the hook bundles, every public library and the distributed CLAUDE.md', () => {
		expect(step_names()).toStrictEqual([
			'bin',
			'hooks',
			'commands',
			...PUBLIC_LIBRARIES,
			'claude-md',
		])
	})

	it('names each step once, so no output is written by two concurrent steps', () => {
		const names = step_names()

		expect(new Set(names).size).toBe(names.length)
	})

	// The build must leave the git tree unchanged: `.codex/hooks.json` is committed, so it is
	// regenerated by hand and guarded by the gate's parity test, never rewritten here.
	it('does not regenerate the committed Codex hooks file', () => {
		expect(step_names().some((name) => name.includes('codex'))).toBe(false)
	})
})
