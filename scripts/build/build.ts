#!/usr/bin/env tsx
import { fileURLToPath } from 'node:url'
import { error_text } from '#scripts/lib/error-message'
import { OUTFILE as BIN_OUTFILE, build_bin } from './build-bin'
import { build_claude_md } from './build-claude-md'
import { build_commands } from './build-commands'
import { build_hooks, OUT_DIR as HOOKS_OUT_DIR } from './build-hooks'
import { build_library, PUBLIC_LIBRARIES } from './build-library'

interface BuildStep {
	name: string
	run: () => Promise<string>
}

async function bin_step(): Promise<string> {
	await build_bin()

	return BIN_OUTFILE
}

async function hooks_step(): Promise<string> {
	await build_hooks()

	return HOOKS_OUT_DIR
}

async function library_step(name: string): Promise<string> {
	const { outfile } = await build_library(name)

	return outfile
}

async function claude_md_step(): Promise<string> {
	return build_claude_md()
}

// Every step `pnpm build` runs. The steps write disjoint paths under
// `dist/`, so they run concurrently from this one entry instead of eight serial `tsx` launches.
// Nothing here writes a git-tracked file: `.codex/hooks.json` is regenerated by hand with
// `tsx scripts/build/build-codex-hooks.ts`, and `codex-project-config.test.ts` fails the gate when
// the committed copy drifts from `.claude/settings.json`.
function build_steps(): ReadonlyArray<BuildStep> {
	return [
		{ name: 'bin', run: bin_step },
		{ name: 'hooks', run: hooks_step },
		{ name: 'commands', run: async () => await build_commands() },
		...PUBLIC_LIBRARIES.map((name) => ({ name, run: async () => await library_step(name) })),
		{ name: 'claude-md', run: claude_md_step },
	]
}

async function build_all(): Promise<ReadonlyArray<string>> {
	return await Promise.all(build_steps().map(async (step) => await step.run()))
}

async function main(): Promise<void> {
	try {
		const outputs = await build_all()

		for (const output of outputs) console.info(`  ✔ ${output} built`)
	} catch (error) {
		console.error(error_text.message_of(error))
		process.exit(1)
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()

export type { BuildStep }
export { build_all, build_steps }
