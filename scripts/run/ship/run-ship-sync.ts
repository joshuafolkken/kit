import {
	FAILURE_MESSAGE_PREFIX,
	FAILURE_REASON_CHECKS,
	FAILURE_REASON_CONFLICT,
} from '#scripts/gh/git-pr-checks-eval'
import { main_merge, type MergeOutcome } from '#scripts/git/main-merge'
import { josh_command, type JoshResult } from '#scripts/josh/josh-run'
import { error_text } from '#scripts/lib/error-message'
import { run_ship_overlap } from './run-ship-overlap'
import { run_ship_scoped } from './run-ship-scoped'
import { run_ship_stop_cause, type Cause } from './run-ship-stop-cause'

// `josh ship` keeps the branch current with the default branch itself: a default branch that moves
// while the pull request opens and CI runs would otherwise stop the followup as `interrupted`, though
// merging the default branch again usually resolves it.
//
// So the merge happens mechanically: before the gate (`sync_stage`), again before the push when the
// default branch moved since (`catch_up`), and when the followup fails after it moved again
// (`followup_stage`). A conflict only on
// generated files is regenerated by the merge itself (`main-merge-regenerate.ts`); any other conflict
// stops the ship as `conflict`, naming the unmerged paths so the resumed session goes straight to them.

const should_forward_stderr = true
const SUCCESS_EXIT_CODE = 0
const FAILURE_EXIT_CODE = 1
// A default branch that keeps moving under a pull request is merged again at most this often per ship;
// past it the followup failure stands, so a busy default branch cannot hold a ship in a loop.
const MAX_MERGE_RETRIES = 2
const CONFLICT_NOTE = 'merging the default branch left unmerged paths:'
const DEFERRED_PREFIX = 'merge deferred to the followup: '
const CURRENT_SUFFIX = ' brings nothing in'
const MERGED_PREFIX = 'merged '
const MERGED_GATE_NOTE =
	'the default branch moved since the sync; the tree merged with it fails the gate:'

// A stage's result, plus the paths a stopped merge left unmerged — carried to the stop prompt.
// `is_skipped` marks a stage that found nothing to do — a review round with nothing to review, a gate
// that reused a green record — so its few seconds are not timed as a run of it. `preconditions` names
// the kinds of the preconditions a stopped preflight found unmet (`run-ship-preflight.ts`). `cause` is the
// one a stopped stage tagged its stop with — a review round, or a red gate over a merged tree
// (`run-ship-stop-cause.ts`).
interface StepResult extends JoshResult {
	is_skipped?: boolean
	conflicts?: ReadonlyArray<string>
	preconditions?: ReadonlyArray<string>
	cause?: Cause
}

async function josh(argv: ReadonlyArray<string>): Promise<JoshResult> {
	return await josh_command.josh_run(argv, should_forward_stderr)
}

// A merge that could not even be attempted — a fetch that failed — reads as a refusal: nothing was
// changed, and the followup still finds a real conflict on GitHub's side.
async function merge_outcome(): Promise<MergeOutcome> {
	try {
		return await main_merge.merge()
	} catch (error) {
		return { kind: 'refused', message: error_text.message_of(error) }
	}
}

function conflict_result(files: ReadonlyArray<string>, lead: string): StepResult {
	const out = [lead, CONFLICT_NOTE, ...files].filter((line) => line !== '').join('\n')

	return { code: FAILURE_EXIT_CODE, out, conflicts: files }
}

function sync_note(outcome: Exclude<MergeOutcome, { kind: 'conflict' }>): string {
	if (outcome.kind === 'refused') return `${DEFERRED_PREFIX}${outcome.message}`

	return outcome.kind === 'current'
		? `${outcome.branch}${CURRENT_SUFFIX}`
		: `${MERGED_PREFIX}${outcome.branch}`
}

// Uncommitted work is committed locally first, never stashed: the merge guard refuses uncommitted work
// the default branch also touches, and a merge deferred past it met its conflict only after the gate,
// both review rounds and CI (joshuafolkken/kit#4708). The commit is not pushed — the commit stage pushes
// it once the gate is green. A merge that changed the tree is checked by that gate, so the push never
// carries an unchecked merge and the gate's record names the merge base the push carries. A refusal
// left — a fetch that failed — does not stop the ship: the commit stage and the followup merge again.
async function commit_locally(title: string, is_dirty: boolean): Promise<JoshResult | undefined> {
	if (!is_dirty) return undefined

	const commit = await josh(['git', '-y', '--skip-push', '--skip-pr', title])

	return commit.code === SUCCESS_EXIT_CODE ? undefined : commit
}

// The merge waits first for any lane whose open pull request changes the same paths
// (`run-ship-overlap.ts`), so it brings that pull request in before the gate rather than meeting it
// as `DIRTY` after CI.
async function sync_stage(issue: string, title: string, is_dirty: boolean): Promise<StepResult> {
	const waited = run_ship_overlap.note(await run_ship_overlap.await_overlap(issue))
	const failed_commit = await commit_locally(title, is_dirty)

	if (failed_commit !== undefined) {
		const out = [waited, failed_commit.out].filter((line) => line !== '').join('\n')

		return { ...failed_commit, out }
	}

	const outcome = await merge_outcome()

	if (outcome.kind === 'conflict') return conflict_result(outcome.files, waited)

	const out = [waited, sync_note(outcome)].filter((line) => line !== '').join('\n')

	return { code: SUCCESS_EXIT_CODE, out }
}

// The tree merged with a default branch that moved is gated before it is pushed: a tree only the
// combined change breaks — two lanes each growing one document inside its cap — stops here, reproduced
// locally rather than met on CI's merge ref (joshuafolkken/kit#4825). The push then carries the tree
// the gate's record describes, so the pre-push hook reuses it rather than re-running the unit suite.
// Its red is tagged a check, so the stage's infrastructure retry never reads test output as an outage.
async function gate_merged(): Promise<StepResult | undefined> {
	const gate = await run_ship_scoped.scoped_gate()

	if (gate.code === SUCCESS_EXIT_CODE) return undefined

	const out = [MERGED_GATE_NOTE, gate.out].filter((line) => line !== '').join('\n')

	return { ...gate, out, cause: run_ship_stop_cause.CAUSE.CHECK }
}

// Before the commit stage pushes: a default branch that moved since the sync stage is merged again and
// the merged tree gated, so the stop lands while the lane still waits on the ship. An unmoved one
// merges nothing and re-runs no gate; a refusal leaves the merge to the followup, as the sync does.
// A tree with no green gate record is gated whatever the merge answered: a re-run commit stage finds
// the merge its red gate stopped on already made, and must not push it without a gate.
async function catch_up(): Promise<StepResult | undefined> {
	const outcome = await merge_outcome()

	if (outcome.kind === 'conflict') return conflict_result(outcome.files, '')
	if (outcome.kind !== 'merged' && (await run_ship_scoped.is_gate_green())) return undefined

	return await gate_merged()
}

async function push_merged(title: string): Promise<StepResult | undefined> {
	const gate = await gate_merged()

	if (gate !== undefined) return gate

	const push = await josh(['git', '-y', '--skip-commit', '--skip-pr', title])

	return push.code === SUCCESS_EXIT_CODE ? undefined : push
}

// The followup's reasons a newer base can change: a red check or a conflict.
const MERGE_FIXABLE_REASONS = [FAILURE_REASON_CHECKS, FAILURE_REASON_CONFLICT]

function names_merge_fixable(text: string | undefined): boolean {
	if (text?.includes(FAILURE_MESSAGE_PREFIX) !== true) return false

	return MERGE_FIXABLE_REASONS.some((reason) => text.includes(reason))
}

// Whether the followup failed on the pull request's checks — a red check or a conflict. A refusal
// before the wait, or a review blocker alone, is not one: its text carries neither reason.
function is_checks_failure(failed: JoshResult): boolean {
	return [failed.out, failed.err].some((text) => names_merge_fixable(text))
}

// The result to stop on, or `undefined` once a clean merge is pushed and the followup can wait again.
// A followup that failed on the checks merges again whenever the default branch moved since the push,
// conflicting or not: a red CI on the merge ref is then reproduced by the local gate or cleared by the
// new push. An unmoved default branch, or any other failure, stands.
async function merge_again(title: string, failed: JoshResult): Promise<StepResult | undefined> {
	if (!is_checks_failure(failed)) return failed

	const outcome = await merge_outcome()

	if (outcome.kind === 'conflict') return conflict_result(outcome.files, failed.out)
	if (outcome.kind !== 'merged') return failed

	return await push_merged(title)
}

// Whether the ship waits on the merge alone, for its stage record (`run_ship_stage.mark_merge_waiting`).
type WaitMark = (is_merge_waiting: boolean) => void

function ignore_wait(): void {
	// A ship with no stage record has no lane place to free.
}

// The wait is marked only while `josh followup` runs: the merge again and its gate run unmarked, so a
// lane gating here still holds its place (joshuafolkken/kit#4466).
async function marked_followup(
	title: string,
	notify: ReadonlyArray<string>,
	mark: WaitMark,
): Promise<JoshResult> {
	mark(true)

	try {
		return await josh(['followup', title, ...notify])
	} finally {
		mark(false)
	}
}

async function followup_attempt(
	title: string,
	notify: ReadonlyArray<string>,
	mark: WaitMark,
	retries: number,
): Promise<StepResult> {
	const result = await marked_followup(title, notify, mark)

	if (result.code === SUCCESS_EXIT_CODE || retries >= MAX_MERGE_RETRIES) return result

	const stop = await merge_again(title, result)

	return stop ?? (await followup_attempt(title, notify, mark, retries + 1))
}

async function followup_stage(
	title: string,
	notify: ReadonlyArray<string>,
	mark: WaitMark = ignore_wait,
): Promise<StepResult> {
	return await followup_attempt(title, notify, mark, 0)
}

const run_ship_sync = {
	CONFLICT_NOTE,
	MAX_MERGE_RETRIES,
	MERGED_GATE_NOTE,
	catch_up,
	followup_stage,
	sync_stage,
}

export type { StepResult, WaitMark }
export { run_ship_sync }
